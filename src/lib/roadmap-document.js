function textOf(value) {
  if (typeof value === 'string' || typeof value === 'number') return String(value)
  if (!value || typeof value !== 'object') return ''
  return value.title || value.name || value.text || ''
}

function heading(text, Paragraph, level) {
  return new Paragraph({ text, heading: level, spacing: { before: 260, after: 100 } })
}

function paragraph(text, Paragraph, TextRun) {
  return new Paragraph({ children: [new TextRun(String(text))], spacing: { after: 100 } })
}

function bullet(text, Paragraph) {
  return new Paragraph({ text: String(text), bullet: { level: 0 }, spacing: { after: 70 } })
}

function listSection(title, items, describe, { Paragraph, HeadingLevel }) {
  if (!Array.isArray(items) || items.length === 0) return []
  return [heading(title, Paragraph, HeadingLevel.HEADING_3), ...items.map((item) => bullet(describe(item), Paragraph))]
}

export async function downloadRoadmapDocument(roadmap) {
  if (!roadmap) throw new Error('Select a saved roadmap before downloading.')
  const { Document, HeadingLevel, Packer, Paragraph, TextRun } = await import('docx')

  const content = [
    new Paragraph({ text: roadmap.role || 'Career Roadmap', heading: HeadingLevel.TITLE }),
    paragraph(`Generated by CareerX · ${new Date().toLocaleDateString()}`, Paragraph, TextRun),
  ]

  if (roadmap.career_overview) {
    content.push(heading('Career overview', Paragraph, HeadingLevel.HEADING_1))
    content.push(paragraph(roadmap.career_overview, Paragraph, TextRun))
  }

  content.push(heading('Timeline', Paragraph, HeadingLevel.HEADING_1))
  content.push(paragraph(roadmap.total_timeline || 'Timeline not available in this saved roadmap.', Paragraph, TextRun))
  if (roadmap.hours_per_week) content.push(paragraph(`Planned study time: ${roadmap.hours_per_week} hours per week`, Paragraph, TextRun))

  if (Array.isArray(roadmap.phases) && roadmap.phases.length) {
    content.push(heading('Journey phases', Paragraph, HeadingLevel.HEADING_1))
    roadmap.phases.forEach((phase, index) => {
      content.push(heading(`${index + 1}. ${phase.phase || `Phase ${index + 1}`}`, Paragraph, HeadingLevel.HEADING_2))
      if (phase.duration) content.push(paragraph(`Duration: ${phase.duration}`, Paragraph, TextRun))
      if (phase.objective) content.push(paragraph(phase.objective, Paragraph, TextRun))
      content.push(...listSection('Skills', phase.skills, (skill) => {
        const name = textOf(skill)
        return typeof skill === 'object' && skill?.rationale ? `${name} — ${skill.rationale}` : name
      }, { Paragraph, HeadingLevel }))
      content.push(...listSection('Portfolio projects', phase.projects, (project) => {
        const title = textOf(project)
        return typeof project === 'object' && project?.description ? `${title} — ${project.description}` : title
      }, { Paragraph, HeadingLevel }))
      content.push(...listSection('Milestones', phase.milestones, textOf, { Paragraph, HeadingLevel }))
    })
  }

  content.push(...listSection('Entry-level positions', roadmap.entry_level_positions, (role) => {
    const title = textOf(role)
    return typeof role === 'object' && role?.fit ? `${title} — ${role.fit}` : title
  }, { Paragraph, HeadingLevel }))
  content.push(...listSection('First 90 days', roadmap.first_90_days, textOf, { Paragraph, HeadingLevel }))
  content.push(...listSection('Planning assumptions', roadmap.assumptions, textOf, { Paragraph, HeadingLevel }))
  content.push(...listSection('Caveats', roadmap.caveats, textOf, { Paragraph, HeadingLevel }))
  content.push(...listSection('Research sources', roadmap.sources, textOf, { Paragraph, HeadingLevel }))

  const document = new Document({
    sections: [{ properties: {}, children: content }],
    styles: {
      default: {
        document: {
          run: { font: 'Aptos', size: 22, color: '262626' },
        },
        heading1: { run: { font: 'Aptos Display', size: 34, bold: true, color: '8A6D16' } },
        heading2: { run: { font: 'Aptos Display', size: 28, bold: true, color: '8A6D16' } },
        heading3: { run: { font: 'Aptos', size: 24, bold: true, color: '4A3B12' } },
      },
    },
  })
  const blob = await Packer.toBlob(document)
  const url = URL.createObjectURL(blob)
  const anchor = window.document.createElement('a')
  const fileName = (roadmap.role || 'career-roadmap').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'career-roadmap'
  anchor.href = url
  anchor.download = `${fileName}-roadmap.docx`
  anchor.click()
  window.setTimeout(() => URL.revokeObjectURL(url), 1000)
}
